import sqlite3,pandas as pd,numpy as np
c=sqlite3.connect('/home/user/uni/keirin_ai/data/keirin.sqlite')
R=pd.read_pickle('ana_R.pkl'); E=pd.read_pickle('ana_E.pkl')
K=pd.read_sql("select e.race_id,e.car_no,e.kimarite,i.sb from entries e left join result_info i using(race_id,car_no)",c)
E=E.merge(K,on=['race_id','car_no'],how='left'); E=E[E.race_id.isin(R.race_id)].copy()
E['finish']=pd.to_numeric(E.finish,errors='coerce'); E['score']=pd.to_numeric(E.score,errors='coerce')
E['lk']=E.race_id+'_'+E.line_id.fillna(-E.car_no).astype(int).astype(str); E['sz']=E.line_size.fillna(1); E['pos']=E.line_pos.fillna(1)
E['得点順位']=E.groupby('race_id').score.rank(ascending=False,method='first')
E['位置']=np.select([E.sz<=1,E.pos==1,E.pos==2],['単騎','先頭','番手'],'3番手以降')
E['B']=E.sb.astype(str).str.contains('B')
w=E[E.finish==1].drop_duplicates('race_id').set_index('race_id'); s=E[E.finish==2].drop_duplicates('race_id').set_index('race_id'); t=E[E.finish==3].drop_duplicates('race_id').set_index('race_id')
R=R.set_index('race_id').join(w[['得点順位','位置','kimarite','B','lk','car_no','sz']].add_prefix('1着_')).join(s[['得点順位','位置','lk']].add_prefix('2着_')).join(t[['得点順位','lk']].add_prefix('3着_'))
R=R.dropna(subset=['1着_得点順位','2着_得点順位','3着_得点順位'])
R['1-2着']=np.where(R['1着_lk']==R['2着_lk'],'同じライン(スジ)','別ライン(スジ違い)')
R['1-2-3着']=np.where((R['1着_lk']==R['2着_lk'])&(R['2着_lk']==R['3着_lk']),'3人同じライン',np.where(R['1-2着'].str.startswith('同'),'1-2だけ同じ','1-2別'))
R['1着の得点順位']=R['1着_得点順位'].clip(upper=5).astype(int).astype(str).replace({'5':'5位以下'})
R['上位3人が3着内']=((R[['1着_得点順位','2着_得点順位','3着_得点順位']]<=3).sum(axis=1)).astype(str)+'人'
R['1着の決まり手']=R['1着_kimarite'].fillna('').str[:1].map({'逃':'逃げ','捲':'捲り','差':'差し','マ':'マーク','ク':'マーク'}).fillna('他')
R['1着がBを取った']=R['1着_B'].map({True:'Bを取った',False:'取っていない'})
R['車番']=R['1着_car_no'].astype(int).astype(str)
R['配当帯']=pd.qcut(R.p3,[0,.5,.8,.9,.95,.99,1],labels=['下位50%','50-80%','80-90%','90-95%','95-99%','上位1%'])
print('3連単配当の帯の境目(円):',R.p3.quantile([.5,.8,.9,.95,.99]).round(-1).astype(int).tolist())
for col in ('1着の得点順位','上位3人が3着内','1着_位置','2着_位置','1-2着','1-2-3着','1着の決まり手','1着がBを取った','並び','グレード','車番'):
    t=pd.crosstab(R[col],R.配当帯,normalize='columns').mul(100).round(1)
    print(f'--- {col}（配当帯ごとの割合 %）'); print(t.to_string())
